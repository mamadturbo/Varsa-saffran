export function getRestoredCatalog(basePath = "/"): CatalogProduct[] {
  if (!basePath.startsWith("/") || /[?#]/.test(basePath))
    throw new Error("Catalog base must be an absolute path");
  const prefix = basePath.replace(/\/+$/g, "");
  return products.map((product) => ({
    ...product,
    image_url: prefix + product.image_url,
  }));
}

